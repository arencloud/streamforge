const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const response=await page.request.get('http://127.0.0.1:8088/api/orders');
 if(!(await response.json()).preview)throw Error('Browser smoke test requires preview mode');
 await page.goto('http://127.0.0.1:8088');
 await page.getByRole('heading',{name:'Create an order'}).waitFor();
 await page.getByLabel('Customer name').fill('Synthetic Browser Order');
 await page.getByLabel('Order amount').fill('49.95');
 await page.getByRole('button',{name:'Create order'}).click();
 await page.getByRole('button',{name:'Mark paid',exact:true}).waitFor();
 await page.getByRole('button',{name:'Mark paid',exact:true}).click();
 await page.getByRole('button',{name:'Mark shipped',exact:true}).waitFor();
 await page.getByRole('button',{name:'Mark shipped',exact:true}).click();
 await page.getByRole('button',{name:'Mark completed',exact:true}).waitFor();
 await page.getByRole('button',{name:'Mark completed',exact:true}).click();
 await page.getByText('This order has reached its final status.',{exact:true}).waitFor();
 if(await page.locator('#error').isVisible())throw Error(await page.locator('#error').textContent());
 await page.screenshot({path:'/tmp/streamforge-dashboard-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/streamforge-dashboard-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Mobile page overflows');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Browser passed: create, pay, ship, complete; desktop/mobile; no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
